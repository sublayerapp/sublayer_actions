require 'net/smtp'
require 'mail'

# Description: Sublayer::Action responsible for sending emails via SMTP using environment variables for configuration.
# This action supports both plain text and HTML content, with optional file attachments.
# It can be used with email services like SendGrid, Amazon SES, or any SMTP server.
#
# Required Environment Variables:
# - SMTP_SERVER: The SMTP server address
# - SMTP_PORT: The SMTP server port
# - SMTP_USERNAME: SMTP authentication username
# - SMTP_PASSWORD: SMTP authentication password
# - SMTP_FROM_EMAIL: Default sender email address
# - SMTP_FROM_NAME: Default sender name (optional)
#
# It is initialized with recipient(s), subject, and content details.
# Returns a boolean indicating whether the email was sent successfully.
#
# Example usage: When you want to send automated email notifications or reports
# generated by AI workflows.

class EmailSendAction < Sublayer::Actions::Base
  def initialize(to:, subject:, text_content: nil, html_content: nil, attachments: [], from_email: nil, from_name: nil)
    @to = Array(to)  # Convert single email to array if necessary
    @subject = subject
    @text_content = text_content
    @html_content = html_content
    @attachments = Array(attachments)
    @from_email = from_email || ENV['SMTP_FROM_EMAIL']
    @from_name = from_name || ENV['SMTP_FROM_NAME'] || @from_email
    
    validate_parameters
    configure_mail
  end

  def call
    begin
      deliver_email
      Sublayer.configuration.logger.log(:info, "Email sent successfully to #{@to.join(', ')}")
      true
    rescue StandardError => e
      error_message = "Error sending email: #{e.message}"
      Sublayer.configuration.logger.log(:error, error_message)
      raise StandardError, error_message
    end
  end

  private

  def validate_parameters
    raise ArgumentError, 'Recipient email(s) required' if @to.empty?
    raise ArgumentError, 'Subject required' if @subject.nil? || @subject.empty?
    raise ArgumentError, 'Either text or HTML content required' if @text_content.nil? && @html_content.nil?
    validate_smtp_settings
  end

  def validate_smtp_settings
    required_env_vars = %w[SMTP_SERVER SMTP_PORT SMTP_USERNAME SMTP_PASSWORD SMTP_FROM_EMAIL]
    missing_vars = required_env_vars.select { |var| ENV[var].nil? || ENV[var].empty? }
    
    unless missing_vars.empty?
      raise StandardError, "Missing required environment variables: #{missing_vars.join(', ')}"
    end
  end

  def configure_mail
    Mail.defaults do
      delivery_method :smtp, {
        address: ENV['SMTP_SERVER'],
        port: ENV['SMTP_PORT'],
        user_name: ENV['SMTP_USERNAME'],
        password: ENV['SMTP_PASSWORD'],
        authentication: 'plain',
        enable_starttls_auto: true
      }
    end
  end

  def deliver_email
    Mail.new do |m|
      # Set basic email attributes
      m.from = %Q{#{@from_name} <#{@from_email}>}
      m.to = @to
      m.subject = @subject

      # Handle content
      if @text_content && @html_content
        m.text_part do
          body @text_content
        end
        m.html_part do
          content_type 'text/html; charset=UTF-8'
          body @html_content
        end
      elsif @html_content
        m.content_type = 'text/html; charset=UTF-8'
        m.body = @html_content
      else
        m.body = @text_content
      end

      # Add attachments
      @attachments.each do |attachment|
        m.add_file(attachment)
      end
    end.deliver!
  end
end