require 'aws-sdk-s3'

# Description: Sublayer::Action responsible for uploading files to AWS S3.
# This action enables persistent storage of files in AWS S3, which is particularly useful
# for workflows that generate files that need to be stored or shared.
#
# Requires: 'aws-sdk-s3' gem
# $ gem install aws-sdk-s3
# Or add `gem 'aws-sdk-s3'` to your Gemfile
#
# It is initialized with:
# - bucket: The name of the S3 bucket to upload to
# - file_path: Path to the local file to upload
# - s3_key: The desired path/name for the file in S3 (if nil, uses basename of file_path)
# - acl: Access control for the uploaded file (default: private)
#
# Returns the URL of the uploaded file in S3.
#
# Example usage: When you need to persistently store files generated by other actions,
# such as images from OpenAIImageGenerationAction or files from WriteFileAction.

class S3UploadFileAction < Sublayer::Actions::Base
  def initialize(bucket:, file_path:, s3_key: nil, acl: 'private')
    @bucket = bucket
    @file_path = file_path
    @s3_key = s3_key || File.basename(@file_path)
    @acl = acl
    
    @client = Aws::S3::Client.new(
      access_key_id: ENV['AWS_ACCESS_KEY_ID'],
      secret_access_key: ENV['AWS_SECRET_ACCESS_KEY'],
      region: ENV['AWS_REGION']
    )
  end

  def call
    begin
      validate_file
      upload_file
      generate_url
    rescue Aws::S3::Errors::ServiceError => e
      error_message = "AWS S3 error: #{e.message}"
      Sublayer.configuration.logger.log(:error, error_message)
      raise StandardError, error_message
    rescue StandardError => e
      error_message = "Error uploading file to S3: #{e.message}"
      Sublayer.configuration.logger.log(:error, error_message)
      raise e
    end
  end

  private

  def validate_file
    unless File.exist?(@file_path)
      raise StandardError, "File not found: #{@file_path}"
    end
  end

  def upload_file
    File.open(@file_path, 'rb') do |file|
      @client.put_object(
        bucket: @bucket,
        key: @s3_key,
        body: file,
        acl: @acl
      )
    end
    
    Sublayer.configuration.logger.log(:info, "Successfully uploaded #{@file_path} to S3 bucket #{@bucket} as #{@s3_key}")
  end

  def generate_url
    signer = Aws::S3::Presigner.new(client: @client)
    
    if @acl == 'public-read'
      "https://#{@bucket}.s3.#{ENV['AWS_REGION']}.amazonaws.com/#{@s3_key}"
    else
      # Generate a presigned URL that expires in 1 hour for private files
      signer.presigned_url(
        :get_object,
        bucket: @bucket,
        key: @s3_key,
        expires_in: 3600
      )
    end
  end
end